"""Bundle the line icons in assets/icons/*.svg into template/src/hw/icons.ts.

  python build_icons.py

Every drawable element gets pathLength="1" so the Illus scene can draw it on with one
stroke-dashoffset. Add a concept: drop a 24x24 stroke SVG (Lucide style) into assets/icons and rerun.
"""
import re
import sys
from pathlib import Path

SKILL = Path(__file__).resolve().parent.parent


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    out = {}
    for f in sorted((SKILL / "assets" / "icons").glob("*.svg")):
        body = re.search(r"<svg[^>]*>(.*)</svg>", f.read_text(encoding="utf-8"), re.S).group(1)
        body = re.sub(r"<!--.*?-->", "", body, flags=re.S)
        body = re.sub(r"\s+", " ", body).strip()
        body = re.sub(r"<(path|circle|rect|line|polyline|polygon|ellipse)\b", r'<\1 pathLength="1"', body)
        out[f.stem] = body
    lines = ["// Generated by scripts/build_icons.py from assets/icons (Lucide, ISC licence). Do not edit by hand.",
             "export const ICONS: Record<string, string> = {"]
    lines += [f"  {k!r}: {v!r}," for k, v in out.items()]
    lines.append("};")
    dst = SKILL / "template" / "src" / "hw" / "icons.ts"
    dst.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(len(out), "icons ->", dst)


if __name__ == "__main__":
    main()
